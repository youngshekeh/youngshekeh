-- V129 Contextual Disagreement Intelligence
-- Freeze review context at the post-review anchor snapshot and learn disagreement evidence by context.
-- No hindsight context reconstruction. No automatic weighting, override, promotion, orders, or capital.

create table if not exists public.gold_disagreement_context_events (
  id bigint generated by default as identity primary key,
  disagreement_event_id bigint not null references public.gold_human_machine_disagreement_events(id),
  review_outcome_id bigint not null references public.gold_human_review_outcomes(id),
  review_event_id bigint not null references public.gold_human_review_events(id),
  review_request_id bigint not null references public.gold_trigger_review_requests(id),
  reviewer_user_id uuid not null,
  classifier_version text not null,
  horizon_minutes integer not null,
  event_class text not null,
  transition_code text not null,
  signal_key text not null,
  direction text not null,
  human_stance text not null,
  comparison_state text not null,
  human_advantage_score integer,
  anchor_id bigint not null references public.gold_human_review_anchors(id),
  anchor_snapshot_id bigint not null references public.gold_live_desk_snapshots(id),
  anchor_market_time timestamptz not null,
  anchor_price numeric not null,
  market_status text,
  session_state text,
  daily_bias text,
  daily_structure text,
  state_phase text,
  path_state text,
  desk_state text,
  long_state text,
  short_state text,
  delayed_feed boolean,
  source_snapshot_sha256 text not null,
  source_disagreement_sha256 text not null,
  context_sha256 text not null,
  created_at timestamptz not null default now(),
  unique(disagreement_event_id)
);

alter table public.gold_disagreement_context_events enable row level security;
revoke all privileges on table public.gold_disagreement_context_events from public, anon, authenticated;
grant select, insert on table public.gold_disagreement_context_events to service_role;
grant usage, select on sequence public.gold_disagreement_context_events_id_seq to service_role;

create index if not exists gold_disagreement_context_review_event_idx
  on public.gold_disagreement_context_events(review_event_id,horizon_minutes);
create index if not exists gold_disagreement_context_request_idx
  on public.gold_disagreement_context_events(review_request_id);
create index if not exists gold_disagreement_context_outcome_idx
  on public.gold_disagreement_context_events(review_outcome_id);
create index if not exists gold_disagreement_context_anchor_idx
  on public.gold_disagreement_context_events(anchor_id);
create index if not exists gold_disagreement_context_snapshot_idx
  on public.gold_disagreement_context_events(anchor_snapshot_id);
create index if not exists gold_disagreement_context_reviewer_idx
  on public.gold_disagreement_context_events(reviewer_user_id,horizon_minutes,created_at desc);

create table if not exists public.gold_disagreement_context_cohort_snapshots (
  id bigint generated by default as identity primary key,
  evaluated_at timestamptz not null default now(),
  classifier_version text not null,
  context_dimension text not null,
  context_value text not null,
  horizon_minutes integer not null,
  scorable_disagreements integer not null,
  human_aligned_count integer not null,
  machine_aligned_count integer not null,
  human_alignment_rate_pct numeric,
  human_wilson_lower_pct numeric,
  source_context_max_id bigint not null,
  evidence_state text not null,
  statistics_publication_state text not null,
  automatic_context_weight numeric,
  automatic_promotion boolean not null default false,
  capital_permission text not null default '0R',
  payload_sha256 text not null,
  unique(classifier_version,context_dimension,context_value,horizon_minutes,source_context_max_id)
);

alter table public.gold_disagreement_context_cohort_snapshots enable row level security;
revoke all privileges on table public.gold_disagreement_context_cohort_snapshots from public, anon, authenticated;
grant select, insert on table public.gold_disagreement_context_cohort_snapshots to service_role;
grant usage, select on sequence public.gold_disagreement_context_cohort_snapshots_id_seq to service_role;

create index if not exists gold_disagreement_context_cohort_lookup_idx
  on public.gold_disagreement_context_cohort_snapshots(
    context_dimension,context_value,horizon_minutes,evaluated_at desc
  );

