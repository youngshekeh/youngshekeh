-- V137 Adaptive Paper Risk Governor
-- Parallel challenger to the fixed-1R V133 paper portfolio.
-- This policy governs PAPER risk only. It cannot enable live trading, broker routing, or real capital.

create table if not exists public.gold_adaptive_paper_risk_policies (
  policy_version text primary key,
  launched_at timestamptz not null default now(),
  max_paper_r numeric not null default 1 check (max_paper_r > 0 and max_paper_r <= 1),
  min_paper_r numeric not null default 0.10 check (min_paper_r > 0 and min_paper_r <= 1),
  discovery_sample integer not null default 5 check (discovery_sample >= 1),
  mature_sample integer not null default 30 check (mature_sample >= discovery_sample),
  drawdown_defense_r numeric not null default 2 check (drawdown_defense_r > 0),
  deep_defense_r numeric not null default 3 check (deep_defense_r > drawdown_defense_r),
  loss_streak_defense integer not null default 2 check (loss_streak_defense >= 1),
  loss_streak_deep integer not null default 4 check (loss_streak_deep > loss_streak_defense),
  live_trading_enabled boolean not null default false,
  order_submission_enabled boolean not null default false,
  real_capital_permission text not null default '0R'
);

insert into public.gold_adaptive_paper_risk_policies(
  policy_version,max_paper_r,min_paper_r,discovery_sample,mature_sample,
  drawdown_defense_r,deep_defense_r,loss_streak_defense,loss_streak_deep
) values (
  'v137-adaptive-paper-risk-v1',1,0.10,5,30,2,3,2,4
)
on conflict(policy_version) do nothing;

