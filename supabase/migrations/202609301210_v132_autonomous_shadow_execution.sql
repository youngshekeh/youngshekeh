-- V132 Autonomous Shadow Execution
-- Event-study paper execution for Gold. Uses delayed COMEX structural references only.
-- No broker order route. No real capital. Append-only research ledger.

create table if not exists public.gold_shadow_trade_intents (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  transition_id bigint not null references public.gold_live_desk_transitions(id),
  source_snapshot_id bigint not null references public.gold_live_desk_snapshots(id),
  strategy_code text not null,
  side text not null check (side in ('LONG','SHORT')),
  source_market_time timestamptz not null,
  source_price numeric not null,
  stop_price numeric not null,
  target_price numeric not null,
  extension_target_price numeric,
  risk_points numeric not null,
  reward_points numeric not null,
  reference_rr numeric not null,
  market_status text,
  session_state text,
  daily_bias text,
  daily_structure text,
  desk_state text,
  source_payload_sha256 text not null,
  entry_basis text not null default 'DELAYED_COMEX_REFERENCE',
  simulation_mode text not null default 'EVENT_STUDY_SHADOW_ONLY',
  live_order_eligible boolean not null default false,
  live_trading_enabled boolean not null default false,
  broker_adapter_state text not null default 'NOT_CONNECTED',
  intent_sha256 text not null,
  unique(transition_id)
);

alter table public.gold_shadow_trade_intents enable row level security;
revoke all privileges on table public.gold_shadow_trade_intents from public, anon, authenticated;
grant select, insert on table public.gold_shadow_trade_intents to service_role;
grant usage, select on sequence public.gold_shadow_trade_intents_id_seq to service_role;

create index if not exists gold_shadow_trade_intents_snapshot_idx
  on public.gold_shadow_trade_intents(source_snapshot_id);
create index if not exists gold_shadow_trade_intents_strategy_idx
  on public.gold_shadow_trade_intents(strategy_code,created_at desc);

create table if not exists public.gold_shadow_trade_outcomes (
  id bigint generated by default as identity primary key,
  intent_id bigint not null references public.gold_shadow_trade_intents(id),
  resolved_at timestamptz not null default now(),
  resolution_code text not null,
  resolved_snapshot_id bigint not null references public.gold_live_desk_snapshots(id),
  resolved_market_time timestamptz not null,
  entry_price numeric not null,
  exit_price numeric not null,
  gross_pnl_points numeric not null,
  gross_r numeric not null,
  mfe_points numeric not null,
  mae_points numeric not null,
  elapsed_minutes numeric not null,
  observed_primary_target boolean not null,
  observed_stop boolean not null,
  cost_model_state text not null default 'UNAVAILABLE',
  estimated_cost_points numeric,
  net_pnl_points numeric,
  net_r numeric,
  observation_mode text not null default 'SNAPSHOT_OBSERVED',
  intrabar_sequence_claim text not null default 'NOT_INFERRED',
  outcome_sha256 text not null,
  unique(intent_id)
);

alter table public.gold_shadow_trade_outcomes enable row level security;
revoke all privileges on table public.gold_shadow_trade_outcomes from public, anon, authenticated;
grant select, insert on table public.gold_shadow_trade_outcomes to service_role;
grant usage, select on sequence public.gold_shadow_trade_outcomes_id_seq to service_role;

create index if not exists gold_shadow_trade_outcomes_snapshot_idx
  on public.gold_shadow_trade_outcomes(resolved_snapshot_id);
create index if not exists gold_shadow_trade_outcomes_resolved_idx
  on public.gold_shadow_trade_outcomes(resolved_at desc);

