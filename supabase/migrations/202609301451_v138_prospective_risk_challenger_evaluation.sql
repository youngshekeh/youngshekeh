-- V138 Prospective Risk Challenger Evaluation
-- Matched-cohort comparison between V133 fixed-1R control and V137 adaptive challenger.
-- No retrospective backfill, no winner selection, no automatic promotion, no live capital authority.

create table if not exists public.gold_risk_challenger_matched_outcomes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  control_decision_id bigint not null unique references public.gold_shadow_portfolio_decisions(id),
  challenger_decision_id bigint not null unique references public.gold_adaptive_paper_decisions(id),
  control_outcome_id bigint not null unique references public.gold_shadow_portfolio_outcomes(id),
  challenger_outcome_id bigint not null unique references public.gold_adaptive_paper_outcomes(id),
  intent_id bigint not null unique references public.gold_shadow_trade_intents(id),
  side text not null check (side in ('LONG','SHORT')),
  source_market_time timestamptz not null,
  resolved_market_time timestamptz not null,
  resolution_code text not null,
  control_allocated_r numeric not null,
  challenger_allocated_r numeric not null,
  underlying_trade_gross_r numeric not null,
  control_portfolio_gross_r numeric not null,
  challenger_portfolio_gross_r numeric not null,
  challenger_minus_control_gross_r numeric not null,
  cost_model_state text not null,
  control_portfolio_net_r numeric,
  challenger_portfolio_net_r numeric,
  outcome_consistent boolean not null,
  prospective_only boolean not null default true,
  future_performance_used boolean not null default false,
  match_sha256 text not null unique
);

alter table public.gold_risk_challenger_matched_outcomes enable row level security;
revoke all privileges on table public.gold_risk_challenger_matched_outcomes from public, anon, authenticated;
grant select, insert on table public.gold_risk_challenger_matched_outcomes to service_role;
grant usage, select on sequence public.gold_risk_challenger_matched_outcomes_id_seq to service_role;

create index if not exists gold_risk_challenger_matched_resolved_idx
  on public.gold_risk_challenger_matched_outcomes(resolved_market_time,id);
create index if not exists gold_risk_challenger_matched_intent_idx
  on public.gold_risk_challenger_matched_outcomes(intent_id);

drop trigger if exists prevent_v138_matched_outcome_mutation on public.gold_risk_challenger_matched_outcomes;
create trigger prevent_v138_matched_outcome_mutation
before update or delete on public.gold_risk_challenger_matched_outcomes
for each row execute function public.prevent_v125_gold_learning_mutation();

create table if not exists public.gold_risk_challenger_evaluation_snapshots (
  id bigint generated by default as identity primary key,
  evaluated_at timestamptz not null default now(),
  evaluation_version text not null,
  control_policy text not null,
  challenger_policy text not null,
  challenger_launched_at timestamptz not null,
  control_allocations_post_launch integer not null,
  challenger_allocations_post_launch integer not null,
  matched_allocations integer not null,
  matched_resolved integer not null,
  matched_open integer not null,
  control_only_allocations integer not null,
  challenger_only_allocations integer not null,
  public_sample_floor integer not null default 10,
  mature_sample_floor integer not null default 30,
  statistics_withheld boolean not null,
  control_cumulative_gross_r numeric not null,
  challenger_cumulative_gross_r numeric not null,
  challenger_minus_control_cumulative_r numeric not null,
  control_max_drawdown_r numeric not null,
  challenger_max_drawdown_r numeric not null,
  challenger_minus_control_drawdown_r numeric not null,
  loss_damage_reduction_r numeric not null,
  winner_upside_sacrifice_r numeric not null,
  evaluation_state text not null,
  automatic_winner_selection boolean not null default false,
  automatic_policy_promotion boolean not null default false,
  live_trading_enabled boolean not null default false,
  order_submission_enabled boolean not null default false,
  real_capital_permission text not null default '0R',
  snapshot_sha256 text not null unique
);

alter table public.gold_risk_challenger_evaluation_snapshots enable row level security;
revoke all privileges on table public.gold_risk_challenger_evaluation_snapshots from public, anon, authenticated;
grant select, insert on table public.gold_risk_challenger_evaluation_snapshots to service_role;
grant usage, select on sequence public.gold_risk_challenger_evaluation_snapshots_id_seq to service_role;

create index if not exists gold_risk_challenger_eval_time_idx
  on public.gold_risk_challenger_evaluation_snapshots(evaluated_at desc);

drop trigger if exists prevent_v138_eval_snapshot_mutation on public.gold_risk_challenger_evaluation_snapshots;
create trigger prevent_v138_eval_snapshot_mutation
before update or delete on public.gold_risk_challenger_evaluation_snapshots
for each row execute function public.prevent_v125_gold_learning_mutation();

create or replace function public.refresh_v138_gold_risk_challenger_evaluation()
returns jsonb
language plpgsql
set search_path to 'public','extensions','pg_temp'
as $$
declare
  v_version constant text := 'v138-prospective-risk-challenger-evaluation-v1';
  v_control constant text := 'v133-one-slot-first-eligible-v1';
  v_challenger constant text := 'v137-adaptive-one-slot-v1';
  v_risk_policy constant text := 'v137-adaptive-paper-risk-v1';
  v_launch timestamptz;
  r record;
  v_match_sha text;
  v_inserted integer := 0;
  v_control_alloc integer := 0;
  v_challenger_alloc integer := 0;
  v_matched_alloc integer := 0;
  v_matched_resolved integer := 0;
  v_matched_open integer := 0;
  v_control_only integer := 0;
  v_challenger_only integer := 0;
  v_control_cum numeric := 0;
  v_challenger_cum numeric := 0;
  v_delta numeric := 0;
  v_control_dd numeric := 0;
  v_challenger_dd numeric := 0;
  v_dd_delta numeric := 0;
  v_loss_reduction numeric := 0;
  v_upside_sacrifice numeric := 0;
  v_state text;
  v_withheld boolean;
  v_sha text;
  v_id bigint;
begin
  perform public.refresh_v133_gold_shadow_portfolio();
  perform public.refresh_v137_gold_adaptive_paper_portfolio();

  select launched_at into v_launch
  from public.gold_adaptive_paper_risk_policies
  where policy_version=v_risk_policy
  limit 1;

  if v_launch is null then
    return jsonb_build_object(
      'ok',false,'version',v_version,'state','FAIL_CLOSED_V137_LAUNCH_MISSING',
      'statistics_withheld',true,'automatic_winner_selection',false,
      'automatic_policy_promotion',false,'live_trading_enabled',false,
      'order_submission_enabled',false,'real_capital_permission','0R'
    );
  end if;

  for r in
    select
      c.id as control_decision_id,
      a.id as challenger_decision_id,
      co.id as control_outcome_id,
      ao.id as challenger_outcome_id,
      i.id as intent_id,
      i.side,
      i.source_market_time,
      greatest(co.resolved_market_time,ao.resolved_market_time) as resolved_market_time,
      co.resolution_code as control_resolution_code,
      ao.resolution_code as challenger_resolution_code,
      c.allocated_risk_r as control_allocated_r,
      a.allocated_paper_r as challenger_allocated_r,
      co.gross_trade_r as control_trade_gross_r,
      ao.gross_trade_r as challenger_trade_gross_r,
      co.portfolio_gross_r as control_portfolio_gross_r,
      ao.portfolio_gross_r as challenger_portfolio_gross_r,
      co.cost_model_state as control_cost_state,
      ao.cost_model_state as challenger_cost_state,
      co.portfolio_net_r as control_portfolio_net_r,
      ao.portfolio_net_r as challenger_portfolio_net_r
    from public.gold_adaptive_paper_decisions a
    join public.gold_shadow_portfolio_decisions c
      on c.intent_id=a.intent_id and c.policy_version=v_control
    join public.gold_shadow_trade_intents i on i.id=a.intent_id
    join public.gold_shadow_portfolio_outcomes co on co.decision_id=c.id
    join public.gold_adaptive_paper_outcomes ao on ao.decision_id=a.id
    where a.policy_version=v_challenger
      and a.decision='ALLOCATE'
      and c.decision='ALLOCATE'
      and i.created_at>=v_launch
      and not exists (
        select 1 from public.gold_risk_challenger_matched_outcomes m where m.intent_id=i.id
      )
    order by greatest(co.resolved_market_time,ao.resolved_market_time),i.id
  loop
    v_match_sha:=encode(
      extensions.digest(
        convert_to(
          concat_ws('|',
            v_version,r.control_decision_id::text,r.challenger_decision_id::text,
            r.control_outcome_id::text,r.challenger_outcome_id::text,r.intent_id::text,
            r.side,r.source_market_time::text,r.resolved_market_time::text,
            r.control_resolution_code,r.challenger_resolution_code,
            r.control_allocated_r::text,r.challenger_allocated_r::text,
            r.control_trade_gross_r::text,r.challenger_trade_gross_r::text,
            r.control_portfolio_gross_r::text,r.challenger_portfolio_gross_r::text,
            coalesce(r.control_portfolio_net_r::text,''),
            coalesce(r.challenger_portfolio_net_r::text,''),'true','false'
          ),'UTF8'
        ),'sha256'
      ),'hex'
    );

    insert into public.gold_risk_challenger_matched_outcomes(
      control_decision_id,challenger_decision_id,control_outcome_id,challenger_outcome_id,
      intent_id,side,source_market_time,resolved_market_time,resolution_code,
      control_allocated_r,challenger_allocated_r,underlying_trade_gross_r,
      control_portfolio_gross_r,challenger_portfolio_gross_r,
      challenger_minus_control_gross_r,cost_model_state,
      control_portfolio_net_r,challenger_portfolio_net_r,outcome_consistent,
      prospective_only,future_performance_used,match_sha256
    ) values (
      r.control_decision_id,r.challenger_decision_id,r.control_outcome_id,r.challenger_outcome_id,
      r.intent_id,r.side,r.source_market_time,r.resolved_market_time,
      case when r.control_resolution_code=r.challenger_resolution_code
        then r.control_resolution_code else 'RESOLUTION_MISMATCH' end,
      r.control_allocated_r,r.challenger_allocated_r,r.control_trade_gross_r,
      r.control_portfolio_gross_r,r.challenger_portfolio_gross_r,
      r.challenger_portfolio_gross_r-r.control_portfolio_gross_r,
      case when r.control_cost_state=r.challenger_cost_state
        then r.control_cost_state else 'COST_STATE_MISMATCH' end,
      r.control_portfolio_net_r,r.challenger_portfolio_net_r,
      abs(r.control_trade_gross_r-r.challenger_trade_gross_r)<0.000001
        and r.control_resolution_code=r.challenger_resolution_code,
      true,false,v_match_sha
    )
    on conflict(intent_id) do nothing;

    if found then v_inserted:=v_inserted+1; end if;
  end loop;

  select count(*) into v_control_alloc
  from public.gold_shadow_portfolio_decisions c
  join public.gold_shadow_trade_intents i on i.id=c.intent_id
  where c.policy_version=v_control and c.decision='ALLOCATE' and i.created_at>=v_launch;

  select count(*) into v_challenger_alloc
  from public.gold_adaptive_paper_decisions a
  where a.policy_version=v_challenger and a.decision='ALLOCATE';

  select count(*) into v_matched_alloc
  from public.gold_adaptive_paper_decisions a
  join public.gold_shadow_portfolio_decisions c
    on c.intent_id=a.intent_id and c.policy_version=v_control
  join public.gold_shadow_trade_intents i on i.id=a.intent_id
  where a.policy_version=v_challenger
    and a.decision='ALLOCATE' and c.decision='ALLOCATE'
    and i.created_at>=v_launch;

  select count(*) into v_matched_resolved
  from public.gold_risk_challenger_matched_outcomes;

  v_matched_open:=greatest(v_matched_alloc-v_matched_resolved,0);

  select count(*) into v_control_only
  from public.gold_shadow_portfolio_decisions c
  join public.gold_shadow_trade_intents i on i.id=c.intent_id
  where c.policy_version=v_control and c.decision='ALLOCATE' and i.created_at>=v_launch
    and not exists (
      select 1 from public.gold_adaptive_paper_decisions a
      where a.policy_version=v_challenger and a.intent_id=c.intent_id and a.decision='ALLOCATE'
    );

  select count(*) into v_challenger_only
  from public.gold_adaptive_paper_decisions a
  where a.policy_version=v_challenger and a.decision='ALLOCATE'
    and not exists (
      select 1 from public.gold_shadow_portfolio_decisions c
      where c.policy_version=v_control and c.intent_id=a.intent_id and c.decision='ALLOCATE'
    );

  select
    coalesce(sum(control_portfolio_gross_r),0),
    coalesce(sum(challenger_portfolio_gross_r),0),
    coalesce(sum(challenger_minus_control_gross_r),0),
    coalesce(sum(case when underlying_trade_gross_r<0
      then abs(control_portfolio_gross_r)-abs(challenger_portfolio_gross_r) else 0 end),0),
    coalesce(sum(case when underlying_trade_gross_r>0
      then control_portfolio_gross_r-challenger_portfolio_gross_r else 0 end),0)
  into v_control_cum,v_challenger_cum,v_delta,v_loss_reduction,v_upside_sacrifice
  from public.gold_risk_challenger_matched_outcomes
  where outcome_consistent=true;

  with path as (
    select id,resolved_market_time,
      sum(control_portfolio_gross_r) over(order by resolved_market_time,id rows unbounded preceding) as c_cum,
      sum(challenger_portfolio_gross_r) over(order by resolved_market_time,id rows unbounded preceding) as a_cum
    from public.gold_risk_challenger_matched_outcomes
    where outcome_consistent=true
  ), peaks as (
    select id,resolved_market_time,c_cum,a_cum,
      greatest(0::numeric,max(c_cum) over(order by resolved_market_time,id rows unbounded preceding)) as c_peak,
      greatest(0::numeric,max(a_cum) over(order by resolved_market_time,id rows unbounded preceding)) as a_peak
    from path
  )
  select coalesce(max(c_peak-c_cum),0),coalesce(max(a_peak-a_cum),0)
  into v_control_dd,v_challenger_dd
  from peaks;

  v_dd_delta:=v_challenger_dd-v_control_dd;
  v_withheld:=v_matched_resolved<10;

  v_state:=case
    when v_matched_resolved=0 then 'WAITING_FOR_MATCHED_OUTCOMES'
    when v_matched_resolved<10 then 'WITHHELD_SMALL_MATCHED_SAMPLE'
    when v_matched_resolved<30 then 'EARLY_MATCHED_EVIDENCE'
    else 'MATURE_MATCHED_EVIDENCE_REVIEW_ELIGIBLE'
  end;

  v_sha:=encode(
    extensions.digest(
      convert_to(
        concat_ws('|',
          v_version,v_launch::text,v_control_alloc::text,v_challenger_alloc::text,
          v_matched_alloc::text,v_matched_resolved::text,v_matched_open::text,
          v_control_only::text,v_challenger_only::text,v_withheld::text,
          v_control_cum::text,v_challenger_cum::text,v_delta::text,
          v_control_dd::text,v_challenger_dd::text,v_dd_delta::text,
          v_loss_reduction::text,v_upside_sacrifice::text,v_state,
          'false','false','false','false','0R'
        ),'UTF8'
      ),'sha256'
    ),'hex'
  );

  insert into public.gold_risk_challenger_evaluation_snapshots(
    evaluation_version,control_policy,challenger_policy,challenger_launched_at,
    control_allocations_post_launch,challenger_allocations_post_launch,
    matched_allocations,matched_resolved,matched_open,
    control_only_allocations,challenger_only_allocations,
    statistics_withheld,control_cumulative_gross_r,challenger_cumulative_gross_r,
    challenger_minus_control_cumulative_r,control_max_drawdown_r,
    challenger_max_drawdown_r,challenger_minus_control_drawdown_r,
    loss_damage_reduction_r,winner_upside_sacrifice_r,evaluation_state,
    automatic_winner_selection,automatic_policy_promotion,
    live_trading_enabled,order_submission_enabled,real_capital_permission,snapshot_sha256
  ) values (
    v_version,v_control,v_challenger,v_launch,
    v_control_alloc,v_challenger_alloc,v_matched_alloc,v_matched_resolved,v_matched_open,
    v_control_only,v_challenger_only,v_withheld,
    v_control_cum,v_challenger_cum,v_delta,v_control_dd,v_challenger_dd,v_dd_delta,
    v_loss_reduction,v_upside_sacrifice,v_state,
    false,false,false,false,'0R',v_sha
  )
  on conflict(snapshot_sha256) do nothing returning id into v_id;

  if v_id is null then
    select id into v_id from public.gold_risk_challenger_evaluation_snapshots
    where snapshot_sha256=v_sha limit 1;
  end if;

  return jsonb_build_object(
    'ok',true,'version',v_version,'snapshot_id',v_id,'state',v_state,
    'challenger_launched_at',v_launch,
    'cohort',jsonb_build_object(
      'control_allocations_post_launch',v_control_alloc,
      'challenger_allocations_post_launch',v_challenger_alloc,
      'matched_allocations',v_matched_alloc,'matched_resolved',v_matched_resolved,
      'matched_open',v_matched_open,'control_only_allocations',v_control_only,
      'challenger_only_allocations',v_challenger_only
    ),
    'release',jsonb_build_object(
      'public_sample_floor',10,'mature_sample_floor',30,
      'statistics_withheld',v_withheld,'human_review_eligible',v_matched_resolved>=30
    ),
    'matched_statistics',
      case when v_withheld then null else jsonb_build_object(
        'control_cumulative_gross_r',v_control_cum,
        'challenger_cumulative_gross_r',v_challenger_cum,
        'challenger_minus_control_cumulative_r',v_delta,
        'control_max_drawdown_r',v_control_dd,
        'challenger_max_drawdown_r',v_challenger_dd,
        'challenger_minus_control_drawdown_r',v_dd_delta,
        'loss_damage_reduction_r',v_loss_reduction,
        'winner_upside_sacrifice_r',v_upside_sacrifice
      ) end,
    'internal_audit',jsonb_build_object(
      'matched_rows_inserted',v_inserted,
      'control_cumulative_gross_r',v_control_cum,
      'challenger_cumulative_gross_r',v_challenger_cum,
      'control_max_drawdown_r',v_control_dd,
      'challenger_max_drawdown_r',v_challenger_dd
    ),
    'governance',jsonb_build_object(
      'comparison_scope','MATCHED_PROSPECTIVE_ALLOCATIONS_ONLY',
      'automatic_winner_selection',false,'automatic_policy_promotion',false,
      'future_performance_selection',false,'live_trading_enabled',false,
      'order_submission_enabled',false,'real_capital_permission','0R'
    ),
    'checked_at',now()
  );
end;
$$;

revoke all on function public.refresh_v138_gold_risk_challenger_evaluation()
  from public, anon, authenticated;
grant execute on function public.refresh_v138_gold_risk_challenger_evaluation() to service_role;

do $$
begin
  if not exists(select 1 from cron.job where jobname='tfa-v138-risk-challenger-evaluation') then
    perform cron.schedule(
      'tfa-v138-risk-challenger-evaluation','*/2 * * * *',
      'select public.refresh_v138_gold_risk_challenger_evaluation();'
    );
  end if;
end $$;
