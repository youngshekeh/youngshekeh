-- V127 Review Intelligence
-- Human review -> first valid post-review server capture -> future market-time outcomes -> descriptive reviewer evidence alignment.
-- No trade P&L claim. No automatic weighting, promotion, orders, or capital authority.

create table if not exists public.gold_human_review_anchors (
  id bigint generated by default as identity primary key,
  review_event_id bigint not null references public.gold_human_review_events(id),
  review_request_id bigint not null references public.gold_trigger_review_requests(id),
  reviewer_user_id uuid not null,
  reviewer_role text,
  classifier_version text not null,
  decision text not null,
  signal_key text not null,
  direction text not null,
  review_event_at timestamptz not null,
  anchor_snapshot_id bigint not null references public.gold_live_desk_snapshots(id),
  anchor_captured_at timestamptz not null,
  anchor_market_time timestamptz not null,
  anchor_price numeric not null,
  anchor_delay_seconds numeric not null,
  source_payload_sha256 text not null,
  anchor_sha256 text not null,
  created_at timestamptz not null default now(),
  unique(review_event_id)
);

