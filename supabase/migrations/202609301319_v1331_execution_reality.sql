-- V133.1 Execution Reality
-- Cost-stress research and hard readiness gates before any broker/live-capital path.
-- Stress values are risk-normalized research scenarios, not measured broker costs.

create table if not exists public.gold_shadow_cost_stress (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  outcome_id bigint not null references public.gold_shadow_trade_outcomes(id),
  intent_id bigint not null references public.gold_shadow_trade_intents(id),
  strategy_code text not null,
  scenario_code text not null,
  stress_cost_r numeric not null,
  stress_cost_points numeric not null,
  gross_r numeric not null,
  stress_net_r numeric not null,
  gross_pnl_points numeric not null,
  stress_net_points numeric not null,
  scenario_basis text not null default 'RISK_NORMALIZED_FRICTION_STRESS_NOT_BROKER_MEASUREMENT',
  actual_broker_cost_claim boolean not null default false,
  payload_sha256 text not null,
  unique(outcome_id,scenario_code)
);

alter table public.gold_shadow_cost_stress enable row level security;
revoke all privileges on table public.gold_shadow_cost_stress from public, anon, authenticated;
grant select, insert on table public.gold_shadow_cost_stress to service_role;
grant usage, select on sequence public.gold_shadow_cost_stress_id_seq to service_role;

create index if not exists gold_shadow_cost_stress_outcome_idx on public.gold_shadow_cost_stress(outcome_id);
create index if not exists gold_shadow_cost_stress_intent_idx on public.gold_shadow_cost_stress(intent_id);
create index if not exists gold_shadow_cost_stress_scenario_idx on public.gold_shadow_cost_stress(scenario_code,created_at desc);
create index if not exists gold_shadow_cost_stress_strategy_idx on public.gold_shadow_cost_stress(strategy_code,scenario_code,created_at desc);

create table if not exists public.gold_execution_readiness_snapshots (
  id bigint generated by default as identity primary key,
  evaluated_at timestamptz not null default now(),
  scope_key text not null,
  strategy_code text,
  resolved_sample integer not null,
  source_outcome_max_id bigint not null,
  avg_gross_r numeric,
  avg_net_r_low_stress numeric,
  avg_net_r_moderate_stress numeric,
  avg_net_r_high_stress numeric,
  high_stress_positive_count integer not null,
  high_stress_positive_rate_pct numeric,
  high_stress_total_r numeric,
  sample_state text not null,
  execution_evidence_state text not null,
  broker_adapter_state text not null,
  execution_grade_quote_available boolean not null,
  broker_spread_measured boolean not null,
  slippage_measured boolean not null,
  order_reconciliation_tested boolean not null,
  kill_switch_tested boolean not null,
  live_trading_enabled boolean not null,
  automatic_real_capital boolean not null,
  real_capital_permission text not null,
  blocker_codes jsonb not null default '[]'::jsonb,
  payload_sha256 text not null,
  unique(scope_key,source_outcome_max_id)
);

alter table public.gold_execution_readiness_snapshots enable row level security;
revoke all privileges on table public.gold_execution_readiness_snapshots from public, anon, authenticated;
grant select, insert on table public.gold_execution_readiness_snapshots to service_role;
grant usage, select on sequence public.gold_execution_readiness_snapshots_id_seq to service_role;

create index if not exists gold_execution_readiness_scope_idx
  on public.gold_execution_readiness_snapshots(scope_key,evaluated_at desc);

