-- V133 Shadow Portfolio Brain
-- One virtual Gold slot, first eligible V132 event wins the slot until resolved.
-- No future-performance selection, no reviewer signal, no optimization, no live orders.

create table if not exists public.gold_shadow_portfolio_decisions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  intent_id bigint not null references public.gold_shadow_trade_intents(id),
  transition_id bigint not null references public.gold_live_desk_transitions(id),
  policy_version text not null,
  policy_mode text not null default 'ONE_SLOT_FIRST_ELIGIBLE',
  decision text not null check (decision in ('ALLOCATE','SKIP')),
  decision_reason text not null,
  side text not null,
  source_market_time timestamptz not null,
  source_price numeric not null,
  reference_rr numeric not null,
  max_concurrent_positions integer not null default 1,
  shadow_risk_budget_r numeric not null default 1,
  allocated_risk_r numeric not null default 0,
  conflicting_open_intent_id bigint references public.gold_shadow_trade_intents(id),
  future_performance_used boolean not null default false,
  reviewer_signal_used boolean not null default false,
  live_order_eligible boolean not null default false,
  live_trading_enabled boolean not null default false,
  broker_adapter_state text not null default 'NOT_CONNECTED',
  decision_sha256 text not null,
  unique(intent_id,policy_version)
);

alter table public.gold_shadow_portfolio_decisions enable row level security;
revoke all privileges on table public.gold_shadow_portfolio_decisions from public, anon, authenticated;
grant select, insert on table public.gold_shadow_portfolio_decisions to service_role;
grant usage, select on sequence public.gold_shadow_portfolio_decisions_id_seq to service_role;

create index if not exists gold_shadow_portfolio_decisions_intent_idx
  on public.gold_shadow_portfolio_decisions(intent_id);
create index if not exists gold_shadow_portfolio_decisions_transition_idx
  on public.gold_shadow_portfolio_decisions(transition_id);
create index if not exists gold_shadow_portfolio_decisions_time_idx
  on public.gold_shadow_portfolio_decisions(source_market_time,decision);

create table if not exists public.gold_shadow_portfolio_outcomes (
  id bigint generated by default as identity primary key,
  decision_id bigint not null references public.gold_shadow_portfolio_decisions(id),
  intent_id bigint not null references public.gold_shadow_trade_intents(id),
  shadow_outcome_id bigint not null references public.gold_shadow_trade_outcomes(id),
  resolved_at timestamptz not null default now(),
  resolved_market_time timestamptz not null,
  resolution_code text not null,
  allocated_risk_r numeric not null,
  gross_trade_r numeric not null,
  portfolio_gross_r numeric not null,
  cost_model_state text not null,
  portfolio_net_r numeric,
  outcome_sha256 text not null,
  unique(decision_id),
  unique(shadow_outcome_id)
);

alter table public.gold_shadow_portfolio_outcomes enable row level security;
revoke all privileges on table public.gold_shadow_portfolio_outcomes from public, anon, authenticated;
grant select, insert on table public.gold_shadow_portfolio_outcomes to service_role;
grant usage, select on sequence public.gold_shadow_portfolio_outcomes_id_seq to service_role;

create index if not exists gold_shadow_portfolio_outcomes_intent_idx
  on public.gold_shadow_portfolio_outcomes(intent_id);
create index if not exists gold_shadow_portfolio_outcomes_resolved_idx
  on public.gold_shadow_portfolio_outcomes(resolved_at desc);

drop trigger if exists prevent_v133_portfolio_decision_mutation on public.gold_shadow_portfolio_decisions;
